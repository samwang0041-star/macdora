check_existing_verified_build() {
	[ -f "$RECEIPT_FILE" ] || return 1
	[ -f "$BUILT_DYLIB_PATH" ] || return 1
	[ -f "$FINAL_LIB_PATH" ] || return 1
	[ -f "$FINAL_MANIFEST_JSON" ] || return 1
	verify_cmake_cache_options || return 1
	# shellcheck disable=SC1090
	. "$RECEIPT_FILE"
	[ "${RECEIPT_INPUT_FINGERPRINT:-}" = "$INPUT_FINGERPRINT" ] || return 1
	local actual_built_sha actual_output_sha actual_manifest_sha
	actual_built_sha=$(sha256_of "$BUILT_DYLIB_PATH")
	actual_output_sha=$(sha256_of "$FINAL_LIB_PATH")
	actual_manifest_sha=$(sha256_of "$FINAL_MANIFEST_JSON")
	[ "${RECEIPT_BUILT_DYLIB_SHA256:-}" = "$actual_built_sha" ] || return 1
	[ "${RECEIPT_OUTPUT_DYLIB_SHA256:-}" = "$actual_output_sha" ] || return 1
	[ "${RECEIPT_MANIFEST_SHA256:-}" = "$actual_manifest_sha" ] || return 1
	grep -Fq "\"librarySHA256\": \"$actual_output_sha\"" "$FINAL_MANIFEST_JSON" || return 1
	verify_library_binary "$FINAL_LIB_PATH" "$VERIFY_LOG" >/dev/null
	return 0
}

