#!/usr/bin/env bash
# Build the upstream MoltenVK used by Macdora's independent GPU backend.
# All downloads, extracted sources, build products, and derived metadata stay
# under .build/moltenvk-upstream. The vendor directory contains only provenance.
set -euo pipefail

die() {
	printf 'build-moltenvk: %s\n' "$*" >&2
	exit 1
}

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPO_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)
VENDOR_DIR=${MOLTENVK_VENDOR_DIR:-"$REPO_ROOT/Vendor/MoltenVK-1.4.2"}
BUILD_ROOT=${MOLTENVK_BUILD_ROOT:-"$REPO_ROOT/.build/moltenvk-upstream"}
DOWNLOADS_DIR="$BUILD_ROOT/downloads"
SOURCES_DIR="$BUILD_ROOT/src"
DERIVED_DIR="$BUILD_ROOT/derived"
OUTPUT_DIR="$BUILD_ROOT/out"
CMAKE_BUILD_DIR="$BUILD_ROOT/build"
CPM_CACHE_DIR="$BUILD_ROOT/cpm-cache"
LOG_DIR="$BUILD_ROOT/logs"
RECEIPT_FILE="$DERIVED_DIR/build-receipt.env"
JOBS=${MOLTENVK_JOBS:-10}

case "$JOBS" in
	''|*[!0-9]*) die "MOLTENVK_JOBS must be a positive integer" ;;
esac
[ "$JOBS" -ge 1 ] || die "MOLTENVK_JOBS must be at least 1"

if [ "${MOLTENVK_REEXEC:-0}" != 1 ]; then
	if [ -z "${DEVELOPER_DIR:-}" ]; then
		for candidate in \
			/Applications/Xcode.app/Contents/Developer \
			/Applications/Xcode-beta.app/Contents/Developer
		do
			if [ -d "$candidate" ]; then
				DEVELOPER_DIR=$candidate
				export DEVELOPER_DIR
				break
			fi
		done
	fi
	# CPM defaults to ~/.cache when this is unset. Keep every generated byte
	# inside the isolated build root instead.
	CPM_SOURCE_CACHE="$BUILD_ROOT/cpm-cache"
	export CPM_SOURCE_CACHE
	# The extracted source trees are inside this outer repository. Without a
	# ceiling, their CMake Git probes would report the outer worktree's HEAD
	# and inject a timestamp into SPIRV-Cross's generated version header.
	GIT_CEILING_DIRECTORIES="$BUILD_ROOT"
	export GIT_CEILING_DIRECTORIES
	MOLTENVK_REEXEC=1
	export MOLTENVK_REEXEC
	exec "$0" "$@"
fi

