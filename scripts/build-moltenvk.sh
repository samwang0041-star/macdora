sha256_of() {
	shasum -a 256 "$1" | awk '{print $1}'
}

require_sha256() {
	local file=$1
	local expected=$2
	local label=$3
	[ -f "$file" ] || die "missing $label: $file"
	local actual
	actual=$(sha256_of "$file")
	[ "$actual" = "$expected" ] || die "$label SHA-256 mismatch: expected $expected, got $actual"
}

fetch_archive() {
	local name=$1
	local url=$2
	local expected=$3
	local archive="$DOWNLOADS_DIR/$name"
	if [ -f "$archive" ]; then
		local actual
		actual=$(sha256_of "$archive")
		if [ "$actual" != "$expected" ]; then
			die "unexpected cached $name SHA-256: $actual"
		fi
	else
		local part="$archive.part"
		rm -f "$part"
		curl --fail --location --retry 3 --retry-delay 2 \
			--connect-timeout 20 --output "$part" "$url"
		local actual
		actual=$(sha256_of "$part")
		[ "$actual" = "$expected" ] || {
			rm -f "$part"
			die "$name SHA-256 mismatch: expected $expected, got $actual"
		}
		mv "$part" "$archive"
	fi
	printf '%s  %s\n' "$(sha256_of "$archive")" "$name"
}

extract_archive_fresh() {
	local archive=$1
	local expected_dir=$2
	rm -rf -- "$SOURCES_DIR/$expected_dir"
	mkdir -p "$SOURCES_DIR"
	tar -xzf "$DOWNLOADS_DIR/$archive" -C "$SOURCES_DIR"
	[ -d "$SOURCES_DIR/$expected_dir" ] || die "archive did not extract $expected_dir"
}

extract_archive() {
	local archive=$1
	local expected_dir=$2
	if [ ! -d "$SOURCES_DIR/$expected_dir" ]; then
		extract_archive_fresh "$archive" "$expected_dir"
	fi
	[ -d "$SOURCES_DIR/$expected_dir" ] || die "archive did not extract $expected_dir"
}

copy_if_missing() {
	local source_file=$1
	local dest_file=$2
	local label=$3
	if [ ! -f "$dest_file" ]; then
		mkdir -p "$(dirname -- "$dest_file")"
		cp "$source_file" "$dest_file"
	fi
	[ -f "$dest_file" ] || die "missing $label: $dest_file"
}

compute_tree_sha256() {
	local dir=$1
	(
		cd "$dir"
		find . -type f -print0 | LC_ALL=C sort -z | xargs -0 shasum -a 256 | sed 's/  \.\//  /'
	) | shasum -a 256 | awk '{print $1}'
}

verify_cmake_cache_options() {
	local cache_file="$CMAKE_BUILD_DIR/CMakeCache.txt"
	[ -f "$cache_file" ] || return 1
	grep -Eq '^MVK_USE_METAL_PRIVATE_API:BOOL=(OFF|0|FALSE)$' "$cache_file" || return 1
	grep -Eq '^CMAKE_OSX_ARCHITECTURES:STRING=arm64$' "$cache_file" || return 1
	grep -Eq '^MVK_EXCLUDE_SPIRV_TOOLS:BOOL=(ON|1|TRUE)$' "$cache_file" || return 1
	grep -Eq '^MVK_BUILD_SHADER_CONVERTER_TOOL:BOOL=(OFF|0|FALSE)$' "$cache_file" || return 1
	return 0
}

verify_library_binary() {
	local lib_path=$1
	local verify_log=$2
	[ -f "$lib_path" ] || die "expected library not found: $lib_path"
	file "$lib_path" | tee "$verify_log"
	otool -L "$lib_path" | tee -a "$verify_log"
	lipo -info "$lib_path" | tee -a "$verify_log"
	local archs
	archs=$(lipo -archs "$lib_path")
	[ "$archs" = arm64 ] || die "expected an arm64-only library, found: $archs"

	local install_name_file="$DERIVED_DIR/install-name.txt"
	local dependencies_file="$DERIVED_DIR/dependencies.txt"
	local exports_file="$DERIVED_DIR/exports.txt"
	otool -D "$lib_path" | tail -n +2 > "$install_name_file"
	otool -L "$lib_path" | tail -n +2 | awk '{print $1}' > "$dependencies_file"
	[ -s "$install_name_file" ] || die "library has no LC_ID_DYLIB"
	local install_name first_load
	install_name=$(head -n 1 "$install_name_file")
	first_load=$(head -n 1 "$dependencies_file")
	[ "$install_name" = "@rpath/libMoltenVK.dylib" ] || die "expected LC_ID_DYLIB @rpath/libMoltenVK.dylib, got $install_name"
	[ "$install_name" = "$first_load" ] || die "otool -D and first otool -L load command disagree"
	grep -q '/usr/lib/libSystem.B.dylib' "$dependencies_file" || die "libSystem dependency missing"
	if grep -Ev '^(@rpath/libMoltenVK(\.[0-9]+)*\.dylib|/System/Library/|/usr/lib/)' "$dependencies_file" \
		| grep -Fvx "$install_name"; then
		die "library has a dependency outside system frameworks"
	fi
	codesign --verify --strict "$lib_path" 2>&1 | tee -a "$verify_log"
	nm -gU "$lib_path" > "$exports_file"
	grep -q '_vkCreateInstance' "$exports_file" || die "vkCreateInstance export missing"
}

