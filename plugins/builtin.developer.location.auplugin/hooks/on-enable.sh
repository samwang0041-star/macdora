#!/system/bin/sh
set -e
umask 077
STATE_FILE="/data/local/tmp/au-location-plugin-state.sh"
if [ ! -f "$STATE_FILE" ]; then
  printf '#!/system/bin/sh\n' > "$STATE_FILE"
  for setting in secure:location_mode secure:mock_location global:location_background_throttle_interval_ms global:location_background_throttle_package_whitelist; do
    namespace="${setting%%:*}"
    name="${setting#*:}"
    original="$(settings get "$namespace" "$name" 2>/dev/null || echo null)"
    if [ "$original" = null ] || [ -z "$original" ]; then
      printf 'settings delete %s %s >/dev/null 2>&1 || true\n' "$namespace" "$name" >> "$STATE_FILE"
    else
      escaped="$(printf '%s' "$original" | sed "s/'/'\\\\''/g")"
      printf "settings put %s %s '%s' >/dev/null 2>&1 || true\n" "$namespace" "$name" "$escaped" >> "$STATE_FILE"
    fi
  done
  chmod 700 "$STATE_FILE"
fi

# Save each application's original grants and modes once, before changing them.
prepare_location_app() {
  app_pkg="$1"
  case "$app_pkg" in
    ''|*[!A-Za-z0-9_.]*|.*|*..*|*.) return 1 ;;
  esac
  case "$app_pkg" in *.*) ;; *) return 1 ;; esac
  pm path "$app_pkg" >/dev/null 2>&1 || return 1
  if ! grep -Fqx "# saved-permissions $app_pkg" "$STATE_FILE"; then
    pkg_dump="$(dumpsys package "$app_pkg" 2>/dev/null || true)"
    for perm in ACCESS_FINE_LOCATION ACCESS_COARSE_LOCATION ACCESS_BACKGROUND_LOCATION; do
      perm_line="$(printf '%s\n' "$pkg_dump" | grep "android.permission.$perm: granted=" | head -n 1 || true)"
      case "$perm_line" in
        *granted=true*) action=grant ;;
        *) action=revoke ;;
      esac
      printf 'pm %s %s android.permission.%s >/dev/null 2>&1 || true\n' "$action" "$app_pkg" "$perm" >> "$STATE_FILE"
    done
    for op in FINE_LOCATION COARSE_LOCATION MONITOR_LOCATION MONITOR_HIGH_POWER_LOCATION MOCK_LOCATION; do
      mode="$(appops get "$app_pkg" "$op" 2>/dev/null | sed -n "s/.*$op: \([a-z_]*\).*/\1/p" | head -n 1 || true)"
      case "$mode" in
        allow|ignore|deny|default|foreground|errored) ;;
        *) mode=default ;;
      esac
      printf 'appops set %s %s %s >/dev/null 2>&1 || true\n' "$app_pkg" "$op" "$mode" >> "$STATE_FILE"
    done
    printf '# saved-permissions %s\n' "$app_pkg" >> "$STATE_FILE"
  fi
  for perm in ACCESS_FINE_LOCATION ACCESS_COARSE_LOCATION ACCESS_BACKGROUND_LOCATION; do
    pm grant "$app_pkg" "android.permission.$perm" >/dev/null 2>&1 || true
  done
  for op in FINE_LOCATION COARSE_LOCATION MONITOR_LOCATION MONITOR_HIGH_POWER_LOCATION; do
    appops set "$app_pkg" "$op" allow >/dev/null 2>&1 || true
  done
  appops set "$app_pkg" MOCK_LOCATION deny >/dev/null 2>&1 || true
}

APP_PACKAGES="$(pm list packages -3 2>/dev/null | sed 's/^package://' | grep -v '^local\.androiduse\.' || true)"
LOCATION_WHITELIST=local.androiduse.plugin.gnss
for app_pkg in $APP_PACKAGES; do
  if prepare_location_app "$app_pkg"; then
    LOCATION_WHITELIST="$LOCATION_WHITELIST,$app_pkg"
  fi
done
settings put secure location_mode 3 >/dev/null 2>&1 || true
settings put secure mock_location 0 >/dev/null 2>&1 || true
settings put global location_background_throttle_interval_ms 0 >/dev/null 2>&1 || true
settings put global location_background_throttle_package_whitelist "$LOCATION_WHITELIST" >/dev/null 2>&1 || true
cmd location set-location-enabled true >/dev/null 2>&1 || true

